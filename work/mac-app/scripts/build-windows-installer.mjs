import {execFileSync} from 'node:child_process';
import {readFile} from 'node:fs/promises';
import path from 'node:path';import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
execFileSync(process.execPath,[path.join(root,'scripts/build-windows-installer-icon.mjs')],{stdio:'inherit'});
const pkg=JSON.parse(await readFile(path.join(root,'windows-stage/package.json'),'utf8'));
const build=process.env.WENJIAN_WINDOWS_BUILD||pkg.buildVersion;
if(!/^\d+$/.test(String(build)))throw Error('Windows build 必须是整数');
const appRoot=path.resolve(process.argv[2]||path.join(root,'release/windows',`Wenjian-${pkg.releaseVersion}-win64`));
const output=path.join(path.resolve(process.env.WENJIAN_WINDOWS_OUTPUT_DIR||path.join(root,'release')),`Wenjian-${pkg.releaseVersion}-build${build}-Windows-x64-Setup.exe`);
execFileSync(process.env.MAKENSIS||'makensis',['-V3','-INPUTCHARSET','UTF8',`-DAPP_DIR=${appRoot}`,`-DOUT_FILE=${output}`,`-DAPP_VERSION=${pkg.releaseVersion}`,`-DAPP_BUILD=${build}`,`-DAPP_DISPLAY_BUILD=${pkg.displayBuild||build}`,path.join(root,'scripts/windows-installer.nsi')],{stdio:'inherit'});
console.log('Windows 安装程序：'+output);
